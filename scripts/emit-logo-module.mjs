import { readFileSync, writeFileSync } from 'node:fs';
const [prims, dest] = process.argv.slice(2);
const p = JSON.parse(readFileSync(prims));
const body = { symbol: p.symbol, standalone: p.standalone, wordEn: p.wordEn, wordAr: p.wordAr };
const out = {};
for (const [k, v] of Object.entries(body)) out[k] = { orange: v.orange, dark: v.dark, ink: v.ink };
writeFileSync(dest, `// Generated by scripts/trace-logo.mjs from the approved artwork on the ARVON brand board.
// Colour-separated trace, 8x board pixels. Replace with the vector master when it is supplied.
export const logoArtwork = ${JSON.stringify(out, null, 2)} as const;
export const arabicLockup = ${JSON.stringify(p.lockups.arabic)} as const;
`);
console.log(out.standalone.ink, p.lockups.arabic);
